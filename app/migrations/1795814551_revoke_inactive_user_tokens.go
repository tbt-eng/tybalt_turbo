package migrations

import (
	"fmt"

	"github.com/pocketbase/pocketbase/core"
	m "github.com/pocketbase/pocketbase/migrations"
)

type inactiveUserTokenRow struct {
	ID string `db:"id"`
}

// This migration signs out every user who counts as inactive, so that a token
// they still hold stops working.
//
// Why this exists:
//   - Sign-in and token refresh refuse an inactive account, and the hooks in
//     hooks/admin_profiles.go give a user a new token key when their admin
//     profile becomes inactive, is created inactive or is deleted. Those hooks
//     act only on a change made after they shipped. A person deactivated
//     before then may still hold a token, which lasts 14 days.
//   - The server code relies on every signed-in caller being active, so those
//     tokens must stop working too.
//
// Who it signs out:
//   - Every user whose admin profile is inactive.
//   - Every user with no admin profile. utilities.IsUserActive counts them as
//     inactive. They cannot sign in with a password ("account setup
//     incomplete") or refresh a token, and a Microsoft sign-in creates an
//     active profile for them. So the only token such a user can hold is one
//     issued before their profile was removed, or by a superuser's
//     impersonation. Signing them out costs nothing: a person who should have
//     access signs in with Microsoft again and gets a profile, as before.
//
// How:
//   - RefreshTokenKey() gives the user a new token key, generated by
//     PocketBase on save. PocketBase signs every token of a user with the
//     tokenKey, so all of them become invalid: auth, file, verification,
//     password-reset and email-change tokens. See
//     1775096237_repair_imported_user_auth_fields.go.
//   - The user is saved without validation, because only tokenKey changes and
//     an older row may fail a rule on a field this migration does not touch.
//   - The users' updated timestamps advance to the migration time.
//
// Running it again signs the same people out again, which is harmless.
//
// Rollback note: the down migration is a no-op. The old token keys are gone,
// and restoring them would make the revoked tokens work again.
func init() {
	m.Register(func(app core.App) error {
		return app.RunInTransaction(func(txApp core.App) error {
			var rows []inactiveUserTokenRow
			if err := txApp.DB().NewQuery(`
				SELECT u.id
				FROM users u
				LEFT JOIN admin_profiles ap ON ap.uid = u.id
				WHERE ap.id IS NULL OR COALESCE(ap.active, 0) = 0
				ORDER BY u.id
			`).All(&rows); err != nil {
				return err
			}

			for _, row := range rows {
				user, err := txApp.FindRecordById("users", row.ID)
				if err != nil {
					return fmt.Errorf("find inactive user %s: %w", row.ID, err)
				}
				user.RefreshTokenKey()
				if err := txApp.SaveNoValidate(user); err != nil {
					return fmt.Errorf("revoke tokens of inactive user %s: %w", row.ID, err)
				}
			}

			return nil
		})
	}, func(app core.App) error {
		return nil
	})
}
